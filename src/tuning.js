export const engineBrakeOf = (s) => 0.4 + (1.2 * (s.engineBraking ?? 50)) / 100 // 50% — как было, 0% — 0,4, 100% — 1,6
export const damperOf = (s, front) => 0.55 + 0.09 * (((front ? s.damperF : s.damperR) ?? 6) - 1) // 6 — как было, 1 — 0,55, 11 — 1,45
export const steerLockOf = (s, T = TUNING) => (T.steerLock * (s.steerLock ?? 24)) / 24 // 24° — как было (0,42 рад)
export const brakeCoolOf = (s) => 0.55 + 0.225 * ((s.brakeDucts ?? 3) - 1) // 3 — как было, 1 — 0,55, 6 — 1,675
export const engineCoolOf = (s) => 1 + 0.075 * ((s.radiator ?? 3) - 3) // 3 — как было, 1 — 0,85 (на медленной трассе мотор горячий и слабее, но не умирает), 6 — 1,225
// открытые воздуховоды и радиаторы — сопротивление воздуха: тормоза 0,5% и радиаторы 0,8% на деление от середины
// балласт: сдвиг центра масс вперёд (+) или назад (−), м. Стандартное шасси ±3 см (±0,9% веса на перед), шасси с балластом
// (build.js, `ballastK` 2) — вдвое больше: его строят легче минимума и добирают вольфрамом, который ставят куда надо
export const BALLAST_STEP = 0.006
export const ballastOf = (s, T = TUNING) => (s.ballast ?? 0) * BALLAST_STEP * (T.ballastK ?? 1)
export const coolDragOf = (s) => 1 + 0.005 * ((s.brakeDucts ?? 3) - 3) + 0.008 * ((s.radiator ?? 3) - 3)

// крылья: доли прижима осей и сопротивление (при 30/30 — ровно как в таблице tuning.js)
export function aeroOf(T) {
  // 0–50, при 30 — ровно как в таблице tuning.js
  const fw = T.setup.frontWing / 50
  const rw = T.setup.rearWing / 50
  return {
    front: T.aeroFrontShare * (T.wingDf0 + T.wingDfK * fw),
    rear: (1 - T.aeroFrontShare) * (T.wingDf0 + T.wingDfK * rw),
    drag: T.wingDrag0 + T.wingDragF * fw + T.wingDragR * rw, // при 30/30 — 1
  }
}

// игровые шкалы → настоящие величины
export function setupPhysics(s) {
  return {
    springF: (150 + (s.suspF - 1) * 7.5) * 1000, // Н/м, 150–450 кН/м
    springR: (150 + (s.suspR - 1) * 7.5) * 1000,
    arbF: (s.arbF - 1) * 10000, // Н/м, 0–200 кН/м
    arbR: (s.arbR - 1) * 10000,
    rideF: (s.rideF - 11) / 1000, // м к базовому клиренсу
    rideR: (s.rideR - 11) / 1000,
  }
}

