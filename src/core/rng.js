// Засеянный ГПСЧ (mulberry32): одно и то же число seed даёт одну и ту же последовательность в Node и в браузере.
// Гонка на сервере берёт из него всё случайное (состав пилотов, стартовые шины, старт, прокол, отказ мотора).
export function seededRandom(seed) {
  let a = seed >>> 0
  return () => {
    a = (a + 0x6d2b79f5) >>> 0
    let t = a
    t = Math.imul(t ^ (t >>> 15), t | 1)
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61)
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296
  }
}
